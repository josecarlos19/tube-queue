export function createTranslator(getLanguage) {
  return (key, count) => {
    const entry = copy[getLanguage()]?.[key] || copy.en[key] || key;
    if (typeof entry === 'string') {
      return entry;
    }
    return entry[count === 1 ? 'one' : 'other'].replace('{count}', count);
  };
}
